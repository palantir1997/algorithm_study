# 가게의 부품 입력 개수
n = int(input())
# 가게 전체 부품을 set(집합)으로 변환
array = set(map(int, input().split()))

"""
🚀 집합(set)에서 in 연산을 할 때 (왜 빠를까?)
반면에 array가 set이면 내부 동작 방식이 완전히 다릅니다. set은 데이터를 저장할 때 해시 함수(Hash Function)라는 걸 써서 각 데이터마다 고유한 주소(위치)를 계산해서 저장합니다.
	•	예를 들어 7이라는 숫자를 넣으면, 해시 함수가 "너는 7번 방에 들어가!" 하고 정해줍니다.
	•	나중에 7 in array라고 물어보면, 파이썬은 처음부터 끝까지 찾아보는 게 아니라 곧바로 7번 방으로 순간 이동해서 있는지 없는지 확인합니다.
	•	데이터가 100만 개가 있든 1,000만 개가 있든 단 한 번의 연산(즉시 확인)으로 끝납니다! (O(1)의 시간 복잡도)

"""

# M 손님 부품 개수
m = int(input())
x = list(map(int, input().split()))

# 손님이 요청한 부품이 set 안에 있는지 O(1) 만에 확인
for i in x:
    if i in array:
        print('yes', end=' ')
    else:
        print('no', end=' ')