"""
문제
동물원에서 막 탈출한 원숭이 한 마리가 세상 구경을 하고 있다.
어느 날 원숭이는 '평화로운 마을'에 잠시 머물렀는데
마침 마을 사람들은 도로 공사 문제로 머리를 맞대고 회의 중이었다.
마을은 N개의 집과 그 집들을 연결하는 M개의 길로 이루어져 있다.
길은 어느 방향으로든지 다닐 수 있는 편리한 길이다.
그리고 길마다 길을 유지하는데 드는 유지비가 있다.
마을의 이장은 마을을 2개의 분리된 마을로 분할할 계획을 세우고 있다.
마을이 너무 커서 혼자서는 관리할 수 없기 때문이다.
마을을 분할할 때는 각 분리된 마을 안에 집들이 서로 연결되도록 분할해야 한다.
각 분리된 마을 안에 있는 임의의 두 집 사이에 경로가 항상 존재해야 한다는 뜻이다.
마을에는 집이 하나 이상 있어야 한다.
그렇게 마을의 이장은 계획을 세우다가 마을 안에 길이 너무 많다는 생각을 하게 되었다.
일단 분리된 두 마을 사이에 있는 길들은 필요가 없으므로 없앨 수 있다.
그리고 각 분리된 마을 안에서도 임의의 두 집 사이에 경로가 항상 존재하게 하면서 길을 더 없앨 수 있다.
마을의 이장은 위 조건을 만족하도록 길들을 모두 없애고 나머지 길의 유지비의 합을 최소로 하고 싶다.
이것을 구하는 프로그램을 작성하시오.

입력 조건
첫째 줄에 집의 개수 N, 길의 개수 M이 주어진다.
N은 2 이상 100,000 이하인 정수이고, M은 1 이상 1,000,000 이하인 정수이다.
그 다음 줄부터 M줄에 걸쳐 길의 정보가 A, B, C 3개의 정수로 공백으로 구분되어 주어지는데
A번 집과 B번 집을 연결하는 길의 유지비가 C(1 <= C <= 1,000) 라는 뜻이다.

출력 조건
첫째 줄에, 길을 없애고 남은 유지비 합의 최솟값을 출력한다.
"""

# --- [도시 분할 계획] ---
# 1. 특정 원소가 속한 집합의 대장(루트)을 찾는 함수 (경로 압축 적용)
def find_parent(parent, x):
    if parent[x] != x:
        parent[x] = find_parent(parent, parent[x])
    return parent[x]

# 2. 두 원소가 속한 집합을 하나로 합치는 함수 (Union)
def union_parent(parent, a, b):
    root_a = find_parent(parent, a)
    root_b = find_parent(parent, b)
    if root_a < root_b:
        parent[root_b] = root_a
    else:
        parent[root_a] = root_b

# --- [메인 프로그램 시작] ---

# 3. 집의 개수 n, 길의 개수 m을 입력받기
n, m = map(int, input().split())
parent = [0] * (n + 1)

# 4. 부모 테이블상에서, 처음에는 각자 자기가 자기 자신을 대장으로 초기화하기
for i in range(n + 1):
    parent[i] = i

# 5. 모든 길(간선) 정보를 담을 리스트와, 최종 비용을 담을 변수 선언하기
edges = []
result = 0

# 6. m개의 길 정보를 입력받아 edges 리스트에 (비용, A, B) 순서로 담기
# [스스로 해보기]
for _ in range(m):
    a, b, c = map(int, input().split())
    edges.append((c, a, b)) # 비용을 첫 번째 원소로 두어야 정렬하기 편합니다!
    

# 7. 간선을 비용 기준으로 오름차순 정렬하기
# [스스로 해보기]
edges.sort()


# 8. 힙이나 반복문을 통해 가장 비용이 큰 간선을 기억하거나, 
# 전체 MST 비용을 구한 뒤 가장 마지막에 더해진(가장 큰) 비용을 빼기 위한 준비
# (힌트: 크루스칼을 돌리면서 선택된 간선들의 비용을 모두 더한 뒤, 가장 큰 값을 빼거나 
# 혹은 N-2개의 간선만 연결될 때까지만 더하는 방법이 있습니다!)
last_cost = 0 # MST에서 가장 비용이 큰 간선을 담을 변수

# 9. 간선을 하나씩 확인하며 크루스칼 알고리즘 수행하기
# [스스로 해보기]
for edge in edges:
    cost, a, b = edge
    # 사이클이 발생하지 않는 경우(즉, 대장이 다른 경우)에만 집합을 합치고 비용 더하기
    if find_parent(parent, a) != find_parent(parent, b):
         union_parent(parent, a, b)
         result += cost
         last_cost = cost # 마지막에 더해지는 값이 가장 큰 비용이 됩니다 (오름차순 정렬이므로!)
    

# 10. 전체 MST 비용에서 가장 비용이 큰 간선(last_cost) 하나를 빼고 최종 결과 출력하기
# [스스로 해보기]
print(result - last_cost)