"""
문제
철수는 온라인으로 컴퓨터공학강의를 듣고 있다.
이때 각 온라인강의는 선수강의가 있을 수 있는데, 선수 강의가 있는 강의는 선수 강의를 먼저 들어야만 해당강의를 들을 수 있다.
예를들어 '알고리즘’ 강의의 선수 강의로 '자료구조'가 존재한다면, ‘자료구조를 들은 이후에 ‘알고리즘' 강의를 들을 수 있다.
철수는 총 N개의 강의를 듣고자 한다. 모든 강의는 1번부터 N번까지의 번호를 가진다.
또한 동시에 여러 개의 강의를 들을 수 있다고 가정한다.
예를 들어 N=3일 때, 3번강의의 선수 강의로 1번과 2번강의가 있고, 1번과 2번강의는 선수강의가 없다고 가정하자.
그리고 각 강의에 대하여 강의 시간이 다음과 같다고 가정하자.
1번 강의: 30시간
2번 강의: 20시간
3번 강의: 40시간
이 경우 1번 강의를 수강하기까지의 최소 시간은 30시간,
2번 강의를 수강하기까지의 최소 시간은 20시간,
3번 강의를 수강하기까지의 최소 시간은 70시간이다.
철수가 듣고자 하는 N개의 강의 정보가 주어졌을 때,
N개의 강의에 대하여 수강하기까지 걸리는 최소 시간을 각각 출력하는 프로그램을 작성하시오.

입력 조건
첫째줄에 철수가 듣고자 하는 강의의 수 N(1≤N≤500)이 주어진다.
다음 N개의 줄에는 각 강의의 강의 시간과 그 강의를 듣기 위해 먼저 들어야하는 강의들의 번호가 자연수로 주어지며, 각 자연수는 공백으로 구분한다.
이때 강의시간은 100,000이하의 자연수이다.
각 강의번호는 1부터 N까지로 구성되며 각줄은 -1로 끝난다.

출력 조건
N개의 강의에 대하여 수강하기까지 걸리는 최소 시간을 한 줄에 하나씩 출력한다
"""
from collections import deque
import copy

# 1. 노드의 개수(강의 수) N 입력받기
n = int(input())

# 2. 모든 노드에 대한 진입차수는 0으로 초기화
indegree = [0] * (n + 1)

# 3. 각 노드에 연결된 간선 정보를 담기 위한 연결 리스트(그래프) 초기화
graph = [[] for _ in range(n + 1)]

# 4. 각 강의의 시간을 담을 리스트 초기화
time = [0] * (n + 1)

# 5. 방향 그래프의 모든 간선 정보를 입력받기 (각 줄은 -1로 끝남)
for i in range(1, n + 1):
    data = list(map(int, input().split()))
    # data[0]은 강의 시간, 그 뒤부터는 선수 강의 번호들이 나오고 마지막은 -1
    time[i] = data[0]
    
    # [스스로 해보기]
    # data[1]부터 시작해서 -1이 나올 때까지 반복하며:
    # - 선수 강의 번호(prev)를 확인하고, 
    # - graph[prev].append(i) 형태로 방향을 설정해주고,
    # - indegree[i] 값을 1 증가시키기!
    # data[1]부터 시작해서 -1이 나올 때까지
    idx = 1
    while data[idx] != -1:
        prev = data[idx]      # 선수 강의 번호
        # 그래서 prev(앞 도미노)가 끝나면 -> i(뒷 도미노)로 신호가 넘어가야 합니다.
        graph[prev].append(i) # 선수 강의(prev)를 듣고 나서 현재 강의(i)로 갈 수 있음!
        indegree[i] += 1      # 현재 강의의 진입차수 1 증가
        idx += 1
    

# 6. 위상 정렬 함수 정의
def topology_sort():
    # 알고리즘 결과를 담을 딥카피 리스트 (강의 시간을 누적해서 최단 시간을 담아둘 용도)
    """
    이 문제에서 딥카피를 왜 썼을까?
    이 문제에서 각 강의의 기본 소요 시간이 들어있는 리스트 이름이 time입니다.
	•	위상 정렬을 하면서 우리는 result라는 리스트에 누적 시간을 갱신해 나가야 합니다. (result[i] = max(..., result[now] + time[i]))
	•	만약 여기서 result = time이라고 해버리면, result를 수정할 때마다 원본 time 리스트까지 같이 오염되어 버려서 다음 테스트 케이스나 알고리즘에 치명적인 오류가 생깁니다.
	•	그래서 "원본 time 리스트는 안전하게 그대로 보존해 두고, 그 값을 베껴서 연산용으로 쓸 독립된 리스트(result)를 새로 만들자!" 하는 의미로 copy.deepcopy(time)을 사용한 것입니다.
    """
    result = copy.deepcopy(time)
    q = deque()

    # [스스로 해보기]
    # 1단계: 진입차수가 0인 노드를 큐에 모두 넣기
    for i in range(1, n + 1):
        if indegree[i] == 0:
            q.append(i)

    # 큐가 빌 때까지 반복
    while q:
        now = q.popleft()

        # [스스로 해보기]
        # 2단계: 현재 노드와 연결된 노드들을 확인하며
        # 현재 노드(now)와 연결된 다음 노드(i)를 확인하며
        for i in graph[now]:
            # result[i] (기존에 기록된 최소 시간)와 
            # result[now] + time[i] (현재 강의까지 오는 데 걸린 시간 + 다음 강의 시간) 중
            # 더 큰 값을 골라야 합니다! (가장 오래 걸리는 걸 기다려야 하니까요)
            result[i] = max(result[i], result[now] + time[i])
            
            # 진입차수 1 빼주기
            indegree[i] -= 1
            
            # 만약 진입차수가 0이 되었다면 큐에 넣기
            if indegree[i] == 0:
                q.append(i)

    # [스스로 해보기]
    # 3단계: 결과 출력하기 (1번부터 N번까지 강의의 최소 수강 시간 출력)
    for i in range(1, n + 1):
        print(result[i])
        

# 함수 실행
topology_sort()