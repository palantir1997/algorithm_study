"""
📖문제
N가지 종류의 화폐가 있다. 이 화폐들의 개수를 최소한으로 이용해서 그 가치의 합이 M원이 되도록 하려고 한다. 이때 각 화폐는 몇 개라도 사용할 수 있으며, 
사용한 화폐의 구성은 같지만 순서만 다른 것은 같은 경우로 구분한다.예를 들어 2원, 3원 단위의 화폐가 있을 때는 
15원을 만들기 위해 3원을 5개 사용하는 것이 가장 최소한의 화폐 개수이다.

입력 조건
 첫째 줄에 N, M이 주어진다. (1 <= N <= 100, 1 <= M <= 10000), 이후 N개의 줄에는 각 화폐의 가치가 주어진다. 
 화폐 가치는 10,000보다 작거나 같은 자연수이다.

출력 조건
첫째 줄에 M원을 만들기 위한 최소한의 화폐 개수를 출력한다. 불가능할 때는 -1을 출력한다.

"""

# N: 화폐 종류 개수, M: 목표 금액
n, m = map(int, input().split())

# 화폐 종류를 리스트에 담습니다.
array = []
for i in range(n):
    array.append(int(input()))

# d[i] 테이블 초기화
# 10001은 M(최대 10000)보다 큰 숫자로, '불가능'을 의미하는 초기값입니다.
# 어떤 금액이든 동전 개수는 절대 10000개를 넘을 수 없으므로 안전한 무한대 값입니다.
d = [10001] * (m + 1)

# [베이스 캠프]
# 0원을 만드는 데 필요한 동전 개수는 0개이므로 0으로 설정합니다.
d[0] = 0

# [DP 핵심 루프]
# 1원부터 M원까지 차례대로 만들 수 있는 최소 동전 개수를 계산합니다.
for i in range(1, m + 1):
    # 주머니 속 모든 화폐 단위(coin)를 하나씩 꺼내봅니다.
    for coin in array:
        # 1. 만약 현재 만들려는 금액(i)이 화폐 단위(coin)보다 크거나 같다면
        # (예: 5원을 만드는데 3원짜리 동전 사용 가능 여부 확인)
        if i >= coin:
            # 2. [점화식]
            # (이전 기록) + (방금 쓴 동전 1개) vs (현재 기록) 중 더 작은 것을 선택
            # d[i-coin]은 (i-coin)원을 만드는 최소 동전 개수입니다.
            d[i] = min(d[i], d[i - coin] + 1)

# 결과 출력
# d[m]이 여전히 10001이라면, 한 번도 갱신되지 않은 것이므로 만들 수 없는 금액입니다.
if d[m] == 10001:
    print(-1)
else:
    print(d[m]) # 문제에서 요구하는 것은 "가치의 합이 M원이 되도록 하는 최소한의 화폐 개수"