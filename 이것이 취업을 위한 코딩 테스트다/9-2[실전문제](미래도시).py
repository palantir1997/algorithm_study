"""
[미래 도시]

방문 판매원 A는 많은 회사가 모여 있는 공중 미래 도시에 있다.
공중 미래 도시에는 1번부터 N번까지의 회사가 있는데 특정 회사끼리는 서로 도로를 통해 연결되어 있다.
방문 판매원 A는 현재 1번 회사에 위치해 있으며, X번 회사에 방문해 물건을 판매하고자 한다.


공중 미래 도시에서 특정 회사에 도착하기 위한 방법은 회사끼리 연결되어 있는 도로를 이용하는 방법이 유일하다.
또한 연결된 2개의 회사는 양방향으로 이동할 수 있다.
공중 미래 도시에서의 도로는 마하의 속도로 사람을 이동시켜주기 때문에 특정 회사와 다른 회사가 도로로 연결되어 있다면,정확히 1만큼의 시간으로 이동할 수 있다.


또한 오늘 방문 판매원 A는 기대하던 소개팅에도 참석하고자 한다. 소개팅의 상대는 K번 회사에 존재한다.
방문 판매원 A는 X번 회사에 가서 물건을 판매하기 전에 먼저 소개팅 상대의 회사에 찾아가서 함께 커피를 마실 예정이다. 
따라서 방문 판매원 A는 1번 회사에서 출발하여 K번 회사를 방문한 뒤에 X번 회사로 가는 것이 목표다.
이때 방문 판매원 A는 가능한 한 빠르게 이동하고자 한다.
방문 판매원이 회사 사이를 이동하게 되는 최소 시간을 계산하는 프로그램을 작성하시오.

 

예를 들어 N = 5, X = 4, K = 5이고 회사 간 도로가 7개면서 각 도로가 다음과 같이 연결되어 있을 때를 가정할 수 있다.

(1번, 2번), (1번, 3번), (1번, 4번), (2번, 4번), (3번, 4번), (3번, 5번), (4번, 5번)

이때 방문 판매원 A가 최종적으로 4번 회사에 가는 경로를 (1번 - 3번 - 5번 - 4번)으로 설정하면,
소개팅에도 참석할 수 있으면서 총 3만큼의 시간으로 이동할 수 있다.
따라서 이 경우 최소 이동 시간은 3이다.

입력 조건
첫째 줄에 전체 회사의 개수 N과 경로의 개수 M이 공백으로 구분되어 차례대로 주어진다. (1 ≤ N, M ≤ 100)
둘째 줄부터 M+1번째 줄에는 연결된 두 회사의 번호가 공백으로 구분되어 주어진다.
M + 2번째 줄에는 X와 K가 공백으로 구분되어 차례대로 주어진다. (1 ≤ K ≤ 100)

출력 조건
첫째 줄에 방문 판매원 A가 K번 회사를 거쳐 X번 회사로 가는 최소 이동 시간을 출력한다.
만약 X번 회사에 도달할 수 없다면 -1을 출력한다.
 
"""

"""
변수정리: 입력받을 때 썼던 변수들 (a, b, x, k)
	•	a, b (간선 연결 정보)
	◦	그냥 "몇 번 회사와 몇 번 회사가 도로로 이어져 있나"를 받을 때 잠깐 쓰고 버리는 임시 이름입니다.
	◦	예를 들어 1번과 2번이 연결되어 있으면 a = 1, b = 2가 되는 식이죠. 의미에 연연할 필요 없이 그냥 '연결된 두 점'이라는 뜻입니다.
	•	x, k (목적지와 거쳐 갈 곳)
	◦	문제에서 입력 마지막 줄에 X와 K를 준다고 했죠?
	◦	그래서 변수 이름을 쓸 때는 graph[1][k] + graph[k][x]처럼 'K를 거쳐서 X로 간다'는 의미에 맞게 조합해서 쓴 것뿐입니다.
"""

INF = int(1e9)  

# n: 회사개수, m: 경로의 개수
n, m = map(int, input().split())

# 2차원 리스트(그래프 지도)를 만들고, 모든 값을 무한대(INF)로 초기화
graph = [[INF] * (n + 1) for _ in range(n + 1)]

# 자기 자신에게 가는 비용은 0으로 초기화 (예: 1번 -> 1번은 0원)
for a in range(1, n + 1):
    for b in range(1, n + 1):
        if a == b:
            graph[a][b] = 0

# 각 간선에 대한 정보를 입력받아, 그 값으로 초기화
for _ in range(m):
    a, b = map(int, input().split())
    graph[a][b] = 1
    graph[b][a] = 1

# 거쳐 갈 노드 x와 최종목적지 노드 k 입력받기
x, k = map(int, input().split())

# 점화식에 따라 플로이드 워셜 수행
"""
3중 반복문이 필요합니다.
	1	거쳐 갈 노드 (i): 1번 회사부터 N번 회사까지 돌아봅니다.
	2	출발 노드 (j): 1번 회사부터 N번 회사까지 돌아봅니다.
	3	도착 노드 (k): 1번 회사부터 N번 회사까지 돌아봅니다.
    국룰 순서: i(거쳐 갈 노드) -> j(출발 노드) -> k(도착 노드) 순으로 바깥에서 안쪽으로 감싸야 합니다.
i, j, k는 문제에서 주어지는 입력값이 아니라, 컴퓨터가 스스로 모든 경우의 수를 다 확인하기 위해 직접 만들어내는 '반복문 카운터(지시자)'이기 때문에, input
으로 안받음
"""
for i in range(1, n + 1):
    for j in range(1, n + 1):
        for k in range(1, n + 1): # 여기 k는 입력받는 k가 아니라 3중 포문에 있는 녀석임!
            graph[j][k] = min(graph[j][k], graph[j][i] + graph[i][k])

# 1번에서 K번을 거쳐 X번으로 가는 총 최소 거리 계산
distance = graph[1][k] + graph[k][x]

# 도달 할 수 없는 경우, -1 출력
if distance >= INF:
    print("-1")
else:
    print(distance)