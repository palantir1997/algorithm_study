"""
문제
학교에서 학생들에게 0번부터 N번까지의 번호를 부여했다.
처음에는 모든 학생이 서로 다른 팀으로 구분되어, 총 N + 1개의 팀이 존재한다.
이때 선생님은 '팀 합치기' 연산과 '같은 팀 여부 확인' 연산을 사용할 수 있다.
'팀 합치기' 연산은 두 팀을 합치는 연산이다.
‘같은 팀 여부 확인' 연산은 특정한 두 학생이 같은 팀에 속하는지를 확인하는 연산이다.
선생님이 M개의 연산을 수행할 수 있을 때,
'같은 팀 여부 확인' 연산에 대한 연산 결과를 출력하는 프로그램을 작성하시오.

입력 조건
첫째 줄에 N, M이 주어진다. M은 입력으로 주어지는 연산의 개수이다. (1 <= N, M <= 100,000)
다음 M개의 줄에는 각각의 연산이 주어진다.
'팀 합치기' 연산은 0 a b 형태로 주어진다.
이는 a번 학생이 속한 팀과 b번 학생이 속한 팀을 합친다는 의미이다.
'같은 팀 여부 확인' 연산은 1 a b 형태로 주어진다.
이는 a번 학생과 b번 학생이 같은 팀에 속해 있는지를 확인하는 연산이다.
a와 b는 N 이하의 양의 정수이다.

출력 조건
'같은 팀 여부 확인' 연산에 대하여 한 줄에 하나씩 YES 혹은 NO로 결과를 출력한다.
"""

# 1. 특정 원소가 속한 집합의 대장(루트)을 찾는 함수 (경로 압축 적용)
# [스스로 해보기] 
# - x의 부모가 자기 자신이 아니라면? 재귀를 타고 올라가서 부모를 찾아내고,
# - 그 값을 parent[x]에 바로 꽂아넣은 뒤(경로 압축) 대장 번호를 리턴하기!
def find_parent(parent, x):
    if parent[x] != x:
        parent[x] = find_parent(parent, parent[x])
    return parent[x]

# 2. 두 원소가 속한 집합을 하나로 합치는 함수 (Union)
# [스스로 해보기]
# - a와 b의 대장을 각각 찾고,
# - 둘 중 누구를 더 대장으로 삼을지 정해서(예: 번호가 더 작은 쪽) parent 테이블 갱신하기!
def union_parent(parent, a, b):
    # 여기에 코드를 채워보세요!
    r_a = find_parent(parent, a)
    r_b = find_parent(parent, b)

    # 대장이 다르다면
    if r_a < r_b:
        parent[r_b] = r_a
    else:
        parent[r_a] = r_b


# --- [메인 프로그램 시작] ---

# 3. n(학생 수), m(연산 횟수)을 입력받기
# [스스로 해보기]
n, m = map(int, input().split()) 
parent = [0] * (n + 1) 

# 4. 부모 테이블 초기화하기
# [스스로 해보기]
# - 0번부터 n번까지 있으니 크기가 n+1인 리스트를 만들고,
# - 처음에는 각자 자기가 자기 자신을 대장으로 가지도록 초기화하기!
for i in range(n + 1):
    parent[i] = i


# 5. m번의 연산 반복문 돌리기
# [스스로 해보기]
# - for _ in range(m): 을 통해 연산 종류(op), a, b를 입력받기
for _ in range(m):
    op, a, b = map(int, input().split())
# - op가 0일 때와 1일 때를 if / else로 나누기!
    # 5-1. op가 0이라면? (팀 합치기 연산)
    # [스스로 해보기]
    # - union_parent 함수 호출하기!
    if op == 0:
        union_parent(parent, a, b)
    # 5-2. op가 1이라면? (같은 팀 여부 확인 연산)
    # [스스로 해보기]
    # - a의 대장과 b의 대장이 같다면 'YES' 출력, 다르면 'NO' 출력하기!
    if op == 1:
        if find_parent(parent, a) == find_parent(parent, b):
            print("YES")
        else:
            print("NO")
